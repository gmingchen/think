package com.think.modules.decision.service;

/**
 * 决策单收口通知（订阅消息下发）
 * <p>
 * 决策单进入「已截止」共有三条路径：评议时限到期扫描、末位评议满员收口、发起人提前结束。
 * 三条路径收口后统一走本服务给发起人发一条订阅提醒，模板字段组装与落地页拼接只在此处保留一份。
 * </p>
 * <p>
 * ⚠️ 必须在事务提交后调用：发送是外部 HTTP（微信接口），放进事务里会长时间持有 decision 行锁，
 * 且发送失败绝不该回滚已经完成的收口。
 * </p>
 *
 * @author 好市民
 */
public interface DecisionNotifyService {

    /**
     * 决策单已截止：给发起人下发一条收口订阅提醒。
     * <p>
     * 全程「发不出不报错」：单据不存在、发起人无记录、无 openid、模板未配置、无配额、微信返回失败，
     * 都只记日志/流水并静默返回；连回表与扣配额的 DB 异常也在实现内整体兜住，
     * 绝不因提醒失败把调用方已提交的收口变成报错响应。
     * </p>
     *
     * @param decisionId 已截止的决策单ID（据此回表取最新标题、截止时间与发起人）
     */
    void remindEnded(Long decisionId);
}
